//! The proper tmux server as a whole: bringing it up, attaching, and shaping windows.

use std::convert::Infallible;
use std::fs;
use std::os::unix::process::CommandExt;
use std::path::{Path, PathBuf};
use std::process::Command;

use anyhow::{Context, Result, bail};

use crate::agents::{Agent, Tree, unique_name};
use crate::config::{Project, Projects, validate_name};
use crate::tmux::{Pane, Role, Server};

pub const SESSION: &str = "proper";
pub const HOME_WINDOW: &str = "home";
pub const SIDEBAR_WIDTH: u16 = 30;
/// tmux wait-for channel signalled by hooks whenever something a sidebar shows may have changed.
pub const CHANGE_CHANNEL: &str = "proper-changed";
const CHANGE_HOOKS: &[&str] = &[
    "session-window-changed",
    "after-new-window",
    "after-kill-pane",
    "window-unlinked",
    "after-split-window",
    "after-set-option",
    "pane-died",
    "pane-exited",
];
const SHIPPED_CONF: &str = include_str!("../tmux.conf");

/// The server's config: the user's own tmux files first, then what proper needs.
pub fn conf_text(home: Option<&Path>) -> String {
    let mut conf = String::from(
        "# generated by proper on every start; put personal settings in ~/.tmux.conf\n",
    );
    if let Some(home) = home {
        conf.push_str(&format!(
            "source-file -q {}\n",
            home.join(".tmux.conf").display()
        ));
        conf.push_str(&format!(
            "source-file -q {}\n",
            home.join(".config/tmux/tmux.conf").display()
        ));
    }
    conf.push_str(SHIPPED_CONF);
    conf.push_str(&format!("set -g main-pane-width {SIDEBAR_WIDTH}\n"));
    for hook in CHANGE_HOOKS {
        conf.push_str(&format!(
            "set-hook -g {hook} 'wait-for -S {CHANGE_CHANNEL}'\n"
        ));
    }
    conf
}

/// The program's file name, which must itself be a valid agent name.
fn agent_name_for(program: &str) -> Result<String> {
    let name = Path::new(program)
        .file_name()
        .map(|n| n.to_string_lossy().to_lowercase())
        .unwrap_or_default();
    validate_name(&name)
        .with_context(|| format!("cannot name an agent after {program:?}; pass --name"))?;
    Ok(name)
}

pub struct Workspace {
    server: Server,
    config_dir: PathBuf,
    exe: PathBuf,
}

impl Workspace {
    /// `exe` is the proper binary that sidebar and hint panes will run.
    pub fn new(server: Server, config_dir: PathBuf, exe: PathBuf) -> Workspace {
        Workspace {
            server,
            config_dir,
            exe,
        }
    }

    pub fn server(&self) -> &Server {
        &self.server
    }

    pub fn conf_path(&self) -> PathBuf {
        self.config_dir.join("tmux.conf")
    }

    pub fn is_running(&self) -> Result<bool> {
        let status = Command::new("tmux")
            .args(["-L", self.server.socket(), "has-session", "-t", SESSION])
            .output()
            .context("failed to spawn tmux")?
            .status;
        Ok(status.success())
    }

    /// Starts the server with a fresh config and the home window: sidebar on the left, hint on the right.
    pub fn bootstrap(&self, home: Option<&Path>) -> Result<()> {
        if self.is_running()? {
            bail!("the {SESSION} session is already running");
        }
        fs::create_dir_all(&self.config_dir)?;
        fs::write(self.conf_path(), conf_text(home))?;

        let conf = self.conf_path().display().to_string();
        let exe = self.exe.display().to_string();
        let hint = self.server.run(&self.server.argv([
            "-f",
            &conf,
            "new-session",
            "-d",
            "-s",
            SESSION,
            "-n",
            HOME_WINDOW,
            "-e",
            &format!("PROPER_CONFIG_DIR={}", self.config_dir.display()),
            "-e",
            &format!("PROPER_SOCKET={}", self.server.socket()),
            "-P",
            "-F",
            "#{pane_id}",
            &exe,
            "hint",
        ]))?;
        let hint = hint.trim();
        self.mark(hint, Role::Hint)?;
        self.add_sidebar(hint)?;
        Ok(())
    }

    /// Splits a sidebar pane off the left of `pane` without stealing focus.
    pub fn add_sidebar(&self, pane: &str) -> Result<String> {
        let exe = self.exe.display().to_string();
        let sidebar = self.server.run(&self.server.argv([
            "split-window",
            "-h",
            "-b",
            "-d",
            "-l",
            &SIDEBAR_WIDTH.to_string(),
            "-t",
            pane,
            "-P",
            "-F",
            "#{pane_id}",
            &exe,
            "sidebar",
        ]))?;
        let sidebar = sidebar.trim().to_string();
        self.mark(&sidebar, Role::Sidebar)?;
        Ok(sidebar)
    }

    /// Everything the sidebar shows: the registry plus whatever agent panes the server has.
    pub fn tree(&self) -> Result<Tree> {
        Ok(Tree::build(&self.server.list_panes()?, &self.projects()?))
    }

    pub fn projects(&self) -> Result<Projects> {
        Projects::load(&self.config_dir)
    }

    pub fn save_projects(&self, projects: &Projects) -> Result<()> {
        projects.save(&self.config_dir)
    }

    /// Opens a window named `project/name` running `command` in the project directory,
    /// adds a sidebar to it and leaves focus in the agent pane.
    pub fn new_agent(
        &self,
        project: &Project,
        name: Option<&str>,
        command: &[String],
    ) -> Result<Agent> {
        let program = command.first().context("agent command is empty")?;
        let tree = self.tree()?;
        let taken: Vec<&str> = tree
            .projects
            .iter()
            .filter(|p| p.name == project.name)
            .flat_map(|p| p.agents.iter().map(|a| a.name.as_str()))
            .collect();
        let name = match name {
            Some(name) => {
                validate_name(name)?;
                if taken.contains(&name) {
                    bail!("{}/{name} already exists", project.name);
                }
                name.to_string()
            }
            None => unique_name(&agent_name_for(program)?, &taken),
        };

        let window = format!("{}/{name}", project.name);
        let path = project.path.display().to_string();
        let mut argv = vec![
            "new-window",
            "-t",
            &format!("{SESSION}:"),
            "-c",
            &path,
            "-n",
            &window,
            "-P",
            "-F",
            "#{pane_id}\t#{window_id}",
        ]
        .into_iter()
        .map(str::to_string)
        .collect::<Vec<_>>();
        argv.extend(command.iter().cloned());
        let ids = self.server.run(&self.server.argv(argv))?;
        let (pane_id, window_id) = ids
            .trim()
            .split_once('\t')
            .context("new-window printed no ids")?;

        self.server.run(&self.server.argv([
            "set-option",
            "-p",
            "-t",
            pane_id,
            "@proper_role",
            Role::Agent.as_str(),
            ";",
            "set-option",
            "-p",
            "-t",
            pane_id,
            "@proper_project",
            &project.name,
            ";",
            "set-option",
            "-p",
            "-t",
            pane_id,
            "@proper_agent",
            &name,
        ]))?;
        self.add_sidebar(pane_id)?;

        Ok(Agent {
            name,
            project: project.name.clone(),
            pane_id: pane_id.to_string(),
            window_id: window_id.to_string(),
            current: true,
            dead: None,
            command: program.clone(),
        })
    }

    /// Repairs proper's own windows: a missing sidebar is split back in, a crashed
    /// sidebar or hint is respawned, and a window left with only a sidebar is closed.
    /// Windows without any proper pane belong to the user and are left alone.
    pub fn heal(&self) -> Result<()> {
        let panes = self.server.list_panes()?;
        let mut windows: Vec<&str> = panes.iter().map(|p| p.window_id.as_str()).collect();
        windows.dedup();
        for window in windows {
            let in_window: Vec<&Pane> = panes.iter().filter(|p| p.window_id == window).collect();
            let sidebar = in_window.iter().find(|p| p.role == Some(Role::Sidebar));
            let content = in_window
                .iter()
                .find(|p| matches!(p.role, Some(Role::Agent | Role::Hint)));
            match (content, sidebar) {
                (Some(content), None) => {
                    self.add_sidebar(&content.id)?;
                    self.server.run(&self.server.argv([
                        "select-layout",
                        "-t",
                        window,
                        "main-vertical",
                    ]))?;
                }
                (None, Some(_)) => self.kill(window)?,
                (Some(content), Some(sidebar)) => {
                    for pane in [content, sidebar]
                        .into_iter()
                        .filter(|p| p.dead.is_some() && p.role != Some(Role::Agent))
                    {
                        self.respawn(&pane.id)?;
                    }
                }
                (None, None) => {}
            }
        }
        Ok(())
    }

    /// Shows an agent's window and puts the cursor in its pane.
    pub fn select(&self, window_id: &str, pane_id: &str) -> Result<()> {
        self.server.run(&self.server.argv([
            "select-window",
            "-t",
            window_id,
            ";",
            "select-pane",
            "-t",
            pane_id,
        ]))?;
        Ok(())
    }

    /// Blocks until a hook signals that panes or windows changed. One signal wakes every waiter.
    pub fn wait_for_change(&self) -> Result<()> {
        self.server
            .run(&self.server.argv(["wait-for", CHANGE_CHANNEL]))?;
        Ok(())
    }

    /// Wakes everything blocked in `wait_for_change`.
    pub fn signal_change(&self) -> Result<()> {
        self.server
            .run(&self.server.argv(["wait-for", "-S", CHANGE_CHANNEL]))?;
        Ok(())
    }

    /// Detaches the client this process runs under; the server and its agents live on.
    pub fn detach(&self) -> Result<()> {
        self.server.run(&self.server.argv(["detach-client"]))?;
        Ok(())
    }

    /// Runs a dead pane's original command again in the same pane. No hook fires for
    /// a respawn, so sidebars are woken explicitly.
    pub fn respawn(&self, pane_id: &str) -> Result<()> {
        self.server
            .run(&self.server.argv(["respawn-pane", "-t", pane_id]))?;
        self.signal_change()
    }

    /// Closes an agent's window, sidebar included.
    pub fn kill(&self, window_id: &str) -> Result<()> {
        self.server
            .run(&self.server.argv(["kill-window", "-t", window_id]))?;
        Ok(())
    }

    fn mark(&self, pane: &str, role: Role) -> Result<()> {
        self.server.run(&self.server.argv([
            "set-option",
            "-p",
            "-t",
            pane,
            "@proper_role",
            role.as_str(),
        ]))?;
        Ok(())
    }

    /// Replaces this process with the tmux client. Only returns on failure to exec.
    pub fn attach(&self) -> Result<Infallible> {
        let err = Command::new("tmux")
            .args(["-L", self.server.socket(), "attach-session", "-t", SESSION])
            .exec();
        Err(err).context("failed to exec tmux attach-session")
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn conf_without_a_home_sources_nothing_of_the_user() {
        let conf = conf_text(None);
        assert!(!conf.contains("source-file"), "{conf}");
        assert!(conf.contains("set -g status off"), "{conf}");
        assert!(
            conf.contains(&format!("set -g main-pane-width {SIDEBAR_WIDTH}")),
            "{conf}"
        );
        assert!(conf.contains("remain-on-exit on"), "{conf}");
        assert!(conf.contains("window-resized"), "{conf}");
    }

    #[test]
    fn conf_with_a_home_sources_both_usual_user_files_first() {
        let conf = conf_text(Some(Path::new("/Users/me")));
        let lines: Vec<&str> = conf
            .lines()
            .filter(|l| !l.starts_with('#') && !l.is_empty())
            .collect();
        assert_eq!(lines[0], "source-file -q /Users/me/.tmux.conf");
        assert_eq!(lines[1], "source-file -q /Users/me/.config/tmux/tmux.conf");
        assert!(lines[2..].contains(&"set -g status off"));
    }

    #[test]
    fn conf_wakes_sidebars_through_a_wait_for_channel_on_every_relevant_change() {
        let conf = conf_text(None);
        for hook in [
            "session-window-changed",
            "after-new-window",
            "after-kill-pane",
            "window-unlinked",
            "after-split-window",
            "after-set-option",
            "pane-died",
            "pane-exited",
        ] {
            let line = format!("set-hook -g {hook} 'wait-for -S {CHANGE_CHANNEL}'");
            assert!(conf.contains(&line), "missing {line} in\n{conf}");
        }
    }

    #[test]
    fn conf_starts_with_a_comment_saying_it_is_generated() {
        assert!(conf_text(None).starts_with("# generated by proper"));
    }
}
